#!/usr/bin/env node
/**
 * Sync the static PROVIDER_MODELS table in cli/src/cli/menus/providers.js
 * from the single source of truth (open-sse/providers registry).
 *
 * The CLI menu shows provider models offline (no server needed), so it keeps a
 * generated copy. Without this script the copy drifts (e.g. missing gpt-5.6-*).
 *
 * Usage:  node scripts/sync-cli-provider-models.mjs [--check]
 *   --check : exit 1 if the file is stale (useful in CI), write nothing.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const TARGET = resolve(ROOT, "cli/src/cli/menus/providers.js");

const HEADER = [
  "// Provider models - AUTO-GENERATED by scripts/sync-cli-provider-models.mjs",
  "// Source: open-sse/providers/registry (single source of truth). Do not edit by hand.",
  "// Regenerate: npm run cli:sync",
].join("\n");

function formatEntry(alias, models) {
  const lines = models.map((m) => `    { id: ${JSON.stringify(m.id)} },`);
  return `  ${JSON.stringify(alias).replace(/^"|"$/g, "")}: [\n${lines.join("\n")}\n  ],`;
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const { PROVIDER_MODELS } = await import(
    pathToFileURL(resolve(ROOT, "open-sse/providers/index.js")).href
  );

  const src = readFileSync(TARGET, "utf8");
  const blockRe =
    /\/\/ Provider models[\s\S]*?\nconst PROVIDER_MODELS = \{[\s\S]*?\n\};/;
  const match = src.match(blockRe);
  if (!match) {
    console.error("[cli-models] PROVIDER_MODELS block not found in", TARGET);
    process.exit(1);
  }

  // Keep the CLI's existing key order; refresh values from the registry.
  // Aliases the CLI knows but the registry dropped (e.g. retired providers)
  // keep their old list so the offline menu never goes blank.
  const oldBlock = match[0];
  const oldKeys = [...oldBlock.matchAll(/^  "?([A-Za-z0-9_-]+)"?: \[/gm)].map(
    (m) => m[1]
  );
  const oldEntries = {};
  for (const key of oldKeys) {
    const re = new RegExp(
      `^  "?${key}"?: \\[([\\s\\S]*?)\\n  \\],`,
      "m"
    );
    const body = oldBlock.match(re);
    if (body) {
      oldEntries[key] = [...body[1].matchAll(/id: "([^"]+)"/g)].map((m) => ({
        id: m[1],
      }));
    }
  }

  const out = [];
  const stale = [];
  for (const key of oldKeys) {
    const fresh = PROVIDER_MODELS[key];
    if (Array.isArray(fresh) && fresh.length > 0) {
      out.push(formatEntry(key, fresh));
      const oldIds = (oldEntries[key] || []).map((m) => m.id).join(",");
      const newIds = fresh.map((m) => m.id).join(",");
      if (oldIds !== newIds) stale.push(key);
    } else {
      // Registry has no catalog for this alias — preserve previous content.
      if (oldEntries[key]?.length) {
        out.push(formatEntry(key, oldEntries[key]));
        console.warn(
          `[cli-models] "${key}" not in registry — kept ${oldEntries[key].length} legacy entries`
        );
      } else {
        console.warn(`[cli-models] "${key}" not in registry and no legacy entries — dropped`);
      }
    }
  }

  const newBlock = `${HEADER}\nconst PROVIDER_MODELS = {\n${out.join("\n")}\n};`;

  if (checkOnly) {
    if (stale.length) {
      console.error(
        `[cli-models] STALE — run "npm run cli:sync". Out of date: ${stale.join(", ")}`
      );
      process.exit(1);
    }
    console.log("[cli-models] up to date");
    return;
  }

  if (!stale.length) {
    console.log("[cli-models] Already in sync — nothing to write");
    return;
  }

  writeFileSync(TARGET, src.replace(blockRe, newBlock), "utf8");
  console.log(
    `[cli-models] Synced ${stale.length} provider(s): ${stale.join(", ")}`
  );
}

main().catch((err) => {
  console.error("[cli-models] Failed:", err.message);
  process.exit(1);
});
